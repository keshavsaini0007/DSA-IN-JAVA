import java.util.*;
public class arithmatic_operators {
    public static void main (String[]args){
        Scanner scan = new Scanner(System.in);
        int i = 1 ; 
        System.out.println(i++);    
        System.out.println(i);
        
        System.out.println();

        int j = 1; 
        System.out.println(++j);
        System.out.println(j);

        System.out.println();

        int k = 1;
        System.out.println(k--);
        System.out.println(k);
        
        System.out.println();

        int l = 1;
        System.out.println(--l);
        System.out.println(l);

        System.out.println();

    }
}
